import { normalizeRussianPhone } from '../src/core/phone';

describe('Russian phone normalization', () => {
  it.each([
    ['', ''],
    ['   ', ''],
    ['+79991234567', '+79991234567'],
    ['+7 (999) 123-45-67', '+79991234567'],
    ['  8 (999) 123-45-67  ', '+79991234567'],
    ['7 999 123 45 67', '+79991234567'],
    ['9991234567', '+79991234567'],
    ['+7 (495) 123-45-67', '+74951234567'],
    ['8 (343) 123-45-67', '+73431234567'],
    ['8001234567', '+78001234567'],
  ])('normalizes %j to %j', (input, expected) => {
    expect(normalizeRussianPhone(input)).toBe(expected);
  });

  it.each([
    '+7 (701) 123-45-67',
    '+7 (601) 123-45-67',
    '+1 999 123 45 67',
    '+8 999 123 45 67',
    '7999123456',
    '799912345678',
    '2991234567',
    'телефон 89991234567',
    '89991234567 доб. 1',
    '++79991234567',
    '7+9991234567',
    '8.999.123.45.67',
    '+79991234567\0',
    '+79991234567\n',
    '+79991234567\r',
    '\t+79991234567',
    '+７９９９１２３４５６７',
    '()-',
    '+',
  ])('rejects invalid content %j', (input) => {
    expect(normalizeRussianPhone(input)).toBeNull();
  });
});
